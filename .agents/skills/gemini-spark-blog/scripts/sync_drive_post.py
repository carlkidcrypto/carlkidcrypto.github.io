#!/usr/bin/env python3
"""Helper script to sync Gemini Spark Agent blog posts from Google Drive.

Capabilities:
1. Detects local Google Drive Auto Blog Posts folder on macOS.
2. Lists pending and posted blog drafts generated by Gemini Spark Agent.
3. Ingests and transforms a draft into Sphinx .rst format with metadata.
4. Registers the new post in source/blog/index.rst (toctree & grid card).
5. Writes '<topic> - POSTED.rst' back to Google Drive with PR & review details.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path


def find_repo_root() -> Path:
    p = Path(__file__).resolve().parent
    while p != p.parent:
        if (p / ".git").exists() or (p / "source" / "blog").exists():
            return p
        p = p.parent
    return Path.cwd().resolve()


REPO_ROOT = find_repo_root()
BLOG_DIR = REPO_ROOT / "source" / "blog"
INDEX_FILE = BLOG_DIR / "index.rst"


def find_google_drive_blog_dir() -> Path | None:
    """Detect local Google Drive 'Auto Blog Posts' directory."""
    # 1. Environment variable override
    env_path = os.environ.get("GOOGLE_DRIVE_BLOG_DIR")
    if env_path:
        p = Path(env_path).expanduser().resolve()
        if p.exists():
            return p

    # 2. Standard macOS CloudStorage paths
    cloud_storage = Path.home() / "Library" / "CloudStorage"
    if cloud_storage.exists():
        matches = list(cloud_storage.glob("GoogleDrive-*/My Drive/Auto Blog Posts"))
        if matches and matches[0].exists():
            return matches[0]
        # Check parent and find
        for drive_dir in cloud_storage.glob("GoogleDrive-*/My Drive"):
            candidate = drive_dir / "Auto Blog Posts"
            if candidate.exists():
                return candidate

    # 3. /Volumes mount
    volumes_match = Path("/Volumes/GoogleDrive/My Drive/Auto Blog Posts")
    if volumes_match.exists():
        return volumes_match

    # 4. ~/Google Drive
    home_drive = Path.home() / "Google Drive" / "My Drive" / "Auto Blog Posts"
    if home_drive.exists():
        return home_drive

    return None


def slug_from_filename(filename: str | Path) -> str:
    """Convert a filename like 'ezsnmp_working_with_mibs_guide.rst' to 'ezsnmp-working-with-mibs-guide'."""
    stem = Path(filename).stem
    # Remove ' - POSTED' if present
    stem = re.sub(r'\s*-\s*POSTED$', '', stem, flags=re.IGNORECASE)
    # Convert underscores to hyphens and lowercase
    slug = stem.replace("_", "-").lower()
    slug = re.sub(r'[^a-z0-9-]+', '', slug)
    return slug


def get_draft_status(drive_dir: Path) -> dict:
    """Inspect Auto Blog Posts and partition files into pending and posted."""
    tracker_path = drive_dir / "ezsnmp Blog Topic Tracker.gdoc"

    raw_files = sorted(drive_dir.glob("*.rst"))
    posted_markers: dict[str, Path] = {}
    drafts: list[Path] = []

    for f in raw_files:
        if f.stem.endswith(" - POSTED") or " - POSTED" in f.name:
            base_stem = f.name.replace(" - POSTED.rst", "")
            posted_markers[base_stem] = f
        else:
            drafts.append(f)

    pending: list[Path] = []
    posted: list[tuple[Path, Path]] = []

    for d in drafts:
        if d.stem in posted_markers:
            posted.append((d, posted_markers[d.stem]))
        else:
            pending.append(d)

    return {
        "pending": pending,
        "posted": posted,
        "tracker": tracker_path if tracker_path.exists() else None,
    }


def parse_draft(draft_path: Path) -> dict:
    """Extract metadata, title, and body from an .rst draft."""
    raw = draft_path.read_text(encoding="utf-8")
    lines = raw.splitlines()

    title = ""
    # Find title from overline/underline or underline
    for i, line in enumerate(lines):
        line_s = line.strip()
        if (
            i + 1 < len(lines)
            and len(line_s) >= 4
            and set(line_s) == {"="}
            and not set(lines[i + 1].strip()).issubset({"="})
            and i + 2 < len(lines)
            and set(lines[i + 2].strip()) == {"="}
        ):
            title = lines[i + 1].strip()
            break
        elif (
            i + 1 < len(lines)
            and set(lines[i + 1].strip()) == {"="}
            and len(lines[i + 1].strip()) >= len(line_s) >= 4
            and not set(line_s).issubset({"="})
        ):
            title = line_s
            break

    if not title:
        title = draft_path.stem.replace("ezsnmp_", "").replace("_", " ").title()

    # Extract field list metadata
    date_str = ""
    reading_time = 5
    tags: list[str] = ["Python", "Networking", "SNMP", "ezsnmp"]
    category = ""

    date_m = re.search(r'^:Date:\s*(.+)$', raw, re.MULTILINE)
    if date_m:
        date_raw = date_m.group(1).strip()
        try:
            dt = datetime.strptime(date_raw, "%Y-%m-%d")
            date_str = dt.strftime("%B %d, %Y")
        except ValueError:
            date_str = date_raw

    time_m = re.search(r'^:Estimated Reading Time:\s*(\d+)', raw, re.MULTILINE)
    if time_m:
        reading_time = int(time_m.group(1))

    tags_m = re.search(r'^:Tags:\s*(.+)$', raw, re.MULTILINE)
    if tags_m:
        raw_tags = tags_m.group(1).split(",")
        tags = [t.strip().title() for t in raw_tags if t.strip()]

    # Clean body: strip field list (:Date:, :Tags:, etc.) and in-page .. contents::
    body_lines: list[str] = []
    skip_contents = False
    past_header = False

    for line in lines:
        stripped = line.strip()
        # Skip title banner at top
        if not past_header:
            if stripped.startswith(":") and stripped.endswith(":"):
                continue
            if re.match(r'^:[A-Za-z -]+:.*$', stripped):
                continue
            if stripped == "":
                continue
            if stripped.startswith(".. contents::"):
                skip_contents = True
                continue
            if skip_contents:
                if stripped.startswith(":") or stripped == "":
                    continue
                skip_contents = False
            # Check if we hit the first section heading
            past_header = True

        if skip_contents:
            if stripped.startswith(":") or stripped == "":
                continue
            skip_contents = False

        if stripped.startswith(".. contents::"):
            skip_contents = True
            continue

        body_lines.append(line)

    clean_body = "\n".join(body_lines).strip()

    # Extract first paragraph as summary
    summary = ""
    for paragraph in clean_body.split("\n\n"):
        p = paragraph.strip()
        if not p.startswith(("=", "-", "~", "..", "*", "#")):
            summary = p.replace("\n", " ").strip()
            if len(summary) > 160:
                summary = summary[:157].rsplit(" ", 1)[0] + "..."
            break

    if not summary:
        summary = f"Practical guide and technical walkthrough for {title}."

    return {
        "title": title,
        "date_str": date_str or datetime.now(timezone.utc).strftime("%B %d, %Y"),
        "reading_time": reading_time,
        "tags": tags,
        "summary": summary,
        "body": clean_body,
    }


def generate_sphinx_rst(parsed: dict, slug: str) -> str:
    """Generate Sphinx-compliant .rst with SEO metadata and Furo note block."""
    title = parsed["title"]
    banner_len = max(len(title), 60)
    banner = "=" * banner_len

    tag_pills = " • ".join(f"`{t}`" for t in parsed["tags"])
    keywords = ", ".join(parsed["tags"] + ["Python", "ezsnmp", "Networking", "DevOps"])

    content = f""".. meta::
   :description: {parsed['summary']}
   :keywords: {keywords}
   :author: Carlos Santos (@carlkidcrypto)
   :property=og:title: {title}
   :property=og:description: {parsed['summary']}
   :property=og:type: article
   :property=og:url: https://carlkidcrypto.github.io/blog/{slug}.html
   :property=og:image: https://carlkidcrypto.github.io/_static/logo.png
   :name=twitter:card: summary
   :name=twitter:title: {title}
   :name=twitter:description: {parsed['summary']}
   :name=twitter:image: https://carlkidcrypto.github.io/_static/logo.png

{banner}
{title}
{banner}

.. note::

   * **Published:** {parsed['date_str']}
   * **Authors:** Written by Gemini 3.8 Flash, Co-Authored & Reviewed by `Carlos Santos (@carlkidcrypto) <https://github.com/carlkidcrypto>`_
   * **Estimated Reading Time:** {parsed['reading_time']} minutes
   * **Tags:** {tag_pills}

{parsed['body']}
"""
    return content


def register_in_index(
    slug: str,
    title: str,
    summary: str,
    date_str: str,
    reading_time: int,
    tags: list[str],
) -> bool:
    """Register slug in source/blog/index.rst (toctree & grid card)."""
    if not INDEX_FILE.exists():
        print(f"Error: {INDEX_FILE} not found.")
        return False

    content = INDEX_FILE.read_text(encoding="utf-8")

    # 1. Add to toctree
    if slug not in content:
        toctree_pattern = r'(\.\. toctree::\s*\n\s*:maxdepth:\s*\d+\s*\n\s*:caption:\s*Articles:\s*\n)'
        match = re.search(toctree_pattern, content)
        if match:
            replacement = match.group(1) + f"\n   {slug}\n"
            content = content[:match.start()] + replacement + content[match.end():]
        else:
            print("Warning: Could not locate .. toctree:: block in index.rst")

    # 2. Add grid card
    if f":link: {slug}" not in content:
        card_tags = " ".join(f"`{t}`" for t in tags[:4])
        card_snippet = f"""   .. grid-item-card:: 📖 {title}
      :link: {slug}
      :link-type: doc

      {summary}

      +++
      📅 *{date_str}* • ⏱️ *{reading_time} min read* • {card_tags}

"""
        grid_pattern = r'(\.\. grid:: 1\s*\n\s*:gutter: \d+\s*\n\n)'
        grid_match = re.search(grid_pattern, content)
        if grid_match:
            content = (
                content[:grid_match.end()]
                + card_snippet
                + content[grid_match.end():]
            )
        else:
            print("Warning: Could not locate .. grid:: block in index.rst")

    INDEX_FILE.write_text(content, encoding="utf-8")
    return True


def create_posted_marker(
    drive_dir: Path,
    draft_stem: str,
    slug: str,
    pr_url: str,
    review_status: str = "All code snippets 100% verified against local daemon",
    ci_status: str = "Audit passed (0 errors) & Sphinx build passing (0 warnings)",
    published_date: str = "",
) -> Path:
    """Create '<draft_stem> - POSTED.rst' in Google Drive."""
    marker_path = drive_dir / f"{draft_stem} - POSTED.rst"
    banner = "=" * max(len(draft_stem) + 9, 67)

    date_line = f"* Published Date: {published_date}\n" if published_date else ""

    text = f"""{banner}
{draft_stem} - POSTED
{banner}

This blog post has been audited, verified, and submitted for publication.

Review & Pull Request
---------------------
* PR: {pr_url}
* Review Status: {review_status}
* CI Status: {ci_status}

Publication Target
------------------
{date_line}* Site URL: https://carlkidcrypto.github.io/blog/{slug}.html
* Repository Path: source/blog/{slug}.rst
* Merge Date Automation: Automated via .github/scripts/stamp_blog_dates.py on merge to main
"""
    marker_path.write_text(text, encoding="utf-8")
    return marker_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Sync blog drafts from Google Drive")
    parser.add_argument("--list", action="store_true", help="List all drafts in Google Drive and their status")
    parser.add_argument("--ingest", type=str, help="Filename or slug of draft to ingest (e.g. ezsnmp_working_with_mibs_guide.rst)")
    parser.add_argument("--mark-posted", type=str, help="Filename or slug to mark as POSTED in Google Drive")
    parser.add_argument("--pr", type=str, help="Pull Request URL when marking as posted")
    parser.add_argument("--review-status", type=str, default="All code snippets 100% verified against local daemon", help="Review status text")
    parser.add_argument("--drive-dir", type=str, help="Explicit path to Google Drive 'Auto Blog Posts' directory")
    args = parser.parse_args(argv)

    drive_dir = Path(args.drive_dir) if args.drive_dir else find_google_drive_blog_dir()

    if not drive_dir or not drive_dir.exists():
        print("Note: Google Drive 'Auto Blog Posts' directory not found.")
        print("Set GOOGLE_DRIVE_BLOG_DIR or install Google Drive for Desktop.")
        return 1

    status = get_draft_status(drive_dir)

    if args.list:
        print(f"\n📂 Google Drive Directory: {drive_dir}\n")
        if status["tracker"]:
            print(f"📋 Topic Tracker: {status['tracker'].name}\n")

        print(f"⏳ PENDING Drafts ({len(status['pending'])}):")
        for p in status["pending"]:
            parsed = parse_draft(p)
            slug = slug_from_filename(p.name)
            print(f"  • {p.name}")
            print(f"    Title: {parsed['title']}")
            print(f"    Date: {parsed['date_str']} | Slug: {slug}")

        print(f"\n✅ POSTED Articles ({len(status['posted'])}):")
        for draft, marker in status["posted"]:
            print(f"  • {draft.name} (Marker: {marker.name})")
        print()
        return 0

    if args.ingest:
        target_name = args.ingest
        # Resolve file path
        candidate = drive_dir / target_name
        if not candidate.exists() and not target_name.endswith(".rst"):
            candidate = drive_dir / f"{target_name}.rst"

        if not candidate.exists():
            # Try finding by slug
            found = [p for p in status["pending"] if slug_from_filename(p.name) == slug_from_filename(target_name)]
            if found:
                candidate = found[0]
            else:
                print(f"Error: Draft '{target_name}' not found in {drive_dir}")
                return 1

        slug = slug_from_filename(candidate.name)
        out_rst = BLOG_DIR / f"{slug}.rst"

        print(f"Ingesting: {candidate.name}")
        parsed = parse_draft(candidate)
        print(f"  Title: {parsed['title']}")
        print(f"  Date: {parsed['date_str']}")
        print(f"  Slug: {slug}")

        sphinx_rst = generate_sphinx_rst(parsed, slug)
        out_rst.write_text(sphinx_rst, encoding="utf-8")
        print(f"  -> Generated: {out_rst.relative_to(REPO_ROOT)}")

        registered = register_in_index(
            slug=slug,
            title=parsed["title"],
            summary=parsed["summary"],
            date_str=parsed["date_str"],
            reading_time=parsed["reading_time"],
            tags=parsed["tags"],
        )
        if registered:
            print(f"  -> Registered in: {INDEX_FILE.relative_to(REPO_ROOT)}")

        print("\nNext steps:")
        print(f"1. Audit: python3 .github/scripts/audit_blog_posts.py")
        print(f"2. Build: .venv/bin/sphinx-build -b html source _build/html -W")
        print(f"3. Open PR and mark posted: python3 {Path(__file__).relative_to(REPO_ROOT)} --mark-posted {candidate.name} --pr <PR_URL>")
        return 0

    if args.mark_posted:
        target_name = args.mark_posted
        if not args.pr:
            print("Error: --pr <url> is required when marking a post as posted.")
            return 1

        candidate = drive_dir / target_name
        if not candidate.exists() and not target_name.endswith(".rst"):
            candidate = drive_dir / f"{target_name}.rst"

        if not candidate.exists():
            all_drafts = status["pending"] + [d for d, _ in status["posted"]]
            found = [p for p in all_drafts if slug_from_filename(p.name) == slug_from_filename(target_name)]
            if found:
                candidate = found[0]
            else:
                print(f"Error: Draft '{target_name}' not found in {drive_dir}")
                return 1

        slug = slug_from_filename(candidate.name)
        parsed = parse_draft(candidate)
        marker = create_posted_marker(
            drive_dir=drive_dir,
            draft_stem=candidate.stem,
            slug=slug,
            pr_url=args.pr,
            review_status=args.review_status,
            published_date=parsed["date_str"],
        )
        print(f"Created Google Drive posted marker: {marker}")
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
